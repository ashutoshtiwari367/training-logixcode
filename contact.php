    <script>
        // FAQ Toggle
        function toggleFaq(btn) {
            const body = btn.nextElementSibling;
            const icon = btn.querySelector('.faq-icon');
            const isOpen = !body.classList.contains('hidden');

            // Close all
            document.querySelectorAll('.faq-body').forEach(b => b.classList.add('hidden'));
            document.querySelectorAll('.faq-icon').forEach(i => i.style.transform = '');

            if (!isOpen) {
                body.classList.remove('hidden');
                icon.style.transform = 'rotate(180deg)';
            }
        }

        // Real Form Submit Handler with AJAX & Inline Validation
        async function handleSubmit(e) {
            e.preventDefault();
            const form = document.getElementById('contactForm');
            const btn = document.getElementById('submitBtn');
            const btnText = document.getElementById('btnText');
            const btnIcon = document.getElementById('btnIcon');
            const formError = document.getElementById('formError');
            const formErrorText = document.getElementById('formErrorText');

            formError.classList.add('hidden');

            const name = form.name.value.trim();
            const phone = form.phone.value.trim();
            const email = form.email.value.trim();
            const message = form.message.value.trim();

            if (!name || !phone || !email || !message) {
                formErrorText.textContent = 'Please fill in all required fields (Name, Phone, Email, and Message).';
                formError.classList.remove('hidden');
                return;
            }

            // Loading state
            btn.disabled = true;
            btnText.textContent = 'Sending...';
            btnIcon.textContent = 'hourglass_top';

            const formData = new FormData(form);

            try {
                const response = await fetch('/api/contact-submit.php', {
                    method: 'POST',
                    body: formData
                });
                const result = await response.json();

                if (result.success) {
                    showToast(result.message || 'Message sent! We will contact you shortly.', false);
                    form.reset();
                } else {
                    formErrorText.textContent = result.error || 'Failed to send message. Please try calling us directly.';
                    formError.classList.remove('hidden');
                }
            } catch (err) {
                // Fallback attempt with relative path
                try {
                    const fallbackResp = await fetch('api/contact-submit.php', {
                        method: 'POST',
                        body: formData
                    });
                    const fallbackResult = await fallbackResp.json();
                    if (fallbackResult.success) {
                        showToast(fallbackResult.message, false);
                        form.reset();
                    } else {
                        formErrorText.textContent = fallbackResult.error || 'An error occurred. Please call +91 8467898854.';
                        formError.classList.remove('hidden');
                    }
                } catch (fallbackErr) {
                    formErrorText.textContent = 'Connection error. Please call +91 8467898854 or WhatsApp us.';
                    formError.classList.remove('hidden');
                }
            } finally {
                btn.disabled = false;
                btnText.textContent = 'Book free demo & send message';
                btnIcon.textContent = 'send';
            }
        }

        function showToast(message, isError) {
            const toast = document.getElementById('toast');
            const toastMsg = document.getElementById('toastMsg');
            const toastIcon = document.getElementById('toastIcon');

            toastMsg.textContent = message;
            toastIcon.textContent = isError ? 'error' : 'check_circle';

            toast.style.opacity = '1';
            toast.style.transform = 'translate(-50%, 0)';
            setTimeout(() => {
                toast.style.opacity = '0';
                toast.style.transform = 'translate(-50%, 20px)';
            }, 4500);
        }
    </script>

